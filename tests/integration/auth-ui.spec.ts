import { test, expect } from "@playwright/test";
import { credentials, confirmationLink } from "../helpers/local-auth";
test("mobile signup, confirmation, onboarding, profile edit, and logout", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const fields = credentials("mobile");
  await page.goto("/signup");
  await page.getByLabel("Email", { exact: true }).fill(fields.email);
  await page.getByLabel("Password", { exact: true }).fill(fields.password);
  await page.getByLabel("Confirm password", { exact: true }).fill(fields.password);
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText("Check your email");
  await page.goto(await confirmationLink(fields.email));
  await expect(page).toHaveURL(/\/onboarding$/);
  await page.getByLabel("Display name").fill("Mobile Student");
  await page.getByLabel("About you", { exact: false }).fill("Learning together.");
  await page.getByRole("button", { name: "Use my device timezone" }).click();
  await page.getByRole("button", { name: "Finish setup" }).click();
  await expect(page.getByRole("heading", { name: "Welcome, Mobile Student" })).toBeVisible();
  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflows).toBe(false);
  await page.getByRole("link", { name: "Edit profile" }).click();
  await page.getByLabel("About you", { exact: false }).fill("An updated introduction.");
  await page.getByRole("button", { name: "Save profile" }).click();
  await expect(page.getByRole("status")).toHaveText("Your profile is saved.");
  await page.reload();
  await expect(page.getByLabel("About you", { exact: false })).toHaveValue("An updated introduction.");
  await page.locator("summary").filter({ hasText: "Menu" }).click();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.goto("/profile");
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel("Email", { exact: true }).fill(fields.email);
  await page.getByLabel("Password", { exact: true }).fill(fields.password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Welcome, Mobile Student" })).toBeVisible();
  await expect(page.getByText("An updated introduction.", { exact: true })).toBeVisible();
});
